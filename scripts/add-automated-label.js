#!/usr/bin/env node
/**
 * Script to add 'automated' label across all MyZubster-Ecosystem repos.
 * Usage: node scripts/add-automated-label.js
 *
 * This script checks all repos in the MyZubster-Ecosystem organization
 * and creates the 'automated' label if it doesn't exist.
 *
 * Requirements: GITHUB_TOKEN environment variable with repo scope.
 */
const https = require('https');

const ORG = 'MyZubster-Ecosystem';
const TOKEN = process.env.GITHUB_TOKEN;
const LABEL = {
  name: 'automated',
  description: 'Issue/PR/comment generated by automated script or bot',
  color: '8B4513'
};

if (!TOKEN) {
  console.error('Error: GITHUB_TOKEN environment variable required');
  process.exit(1);
}

function apiCall(method, path, body) {
  return new Promise((resolve, reject) => {
    const data = body ? JSON.stringify(body) : null;
    const options = {
      hostname: 'api.github.com',
      path: path,
      method: method,
      headers: {
        'Authorization': `Bearer ${TOKEN}`,
        'Accept': 'application/vnd.github.v3+json',
        'Content-Type': 'application/json',
        'User-Agent': 'MyZubster-Automation'
      }
    };
    const req = https.request(options, (res) => {
      let body = '';
      res.on('data', (chunk) => body += chunk);
      res.on('end', () => {
        try { resolve({ status: res.statusCode, data: JSON.parse(body) }); }
        catch (e) { resolve({ status: res.statusCode, data: body }); }
      });
    });
    req.on('error', reject);
    if (data) req.write(data);
    req.end();
  });
}

async function main() {
  console.log(`Fetching repos for ${ORG}...`);
  const reposRes = await apiCall('GET', `/orgs/${ORG}/repos?per_page=100`);
  if (reposRes.status !== 200) {
    console.error(`Failed to fetch repos: ${reposRes.status}`);
    process.exit(1);
  }
  
  const repos = reposRes.data.map(r => r.name);
  console.log(`Found ${repos.length} repos: ${repos.join(', ')}\n`);
  
  for (const repo of repos) {
    console.log(`Checking ${repo}...`);
    // Try to create the label (will fail if it exists, which is fine)
    const createRes = await apiCall('POST', `/repos/${ORG}/${repo}/labels`, LABEL);
    if (createRes.status === 201) {
      console.log(`  ✅ Created 'automated' label in ${repo}`);
    } else if (createRes.status === 422) {
      console.log(`  ⏭️  Label 'automated' already exists in ${repo}`);
    } else {
      console.log(`  ⚠️  Unexpected response (${createRes.status}) for ${repo}`);
    }
  }
  
  console.log('\nDone! All repos checked for automated label.');
}

main().catch(console.error);
